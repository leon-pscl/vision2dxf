import { useState } from 'react'
import { Button, Callout } from '../components/ui'
import { api, RequestError, saveJson, type GenerationPayload } from '../api'
import type { GenerationResponse, Settings } from '../types'

const FILES = [
  { path: '/api/patterns/export/bundle', name: 'pattern-bundle.zip', label: 'Everything (ZIP)', note: 'Pattern, manifest, diagnostics, previews, debug meshes, and production files.' },
  { path: '/api/patterns/export/pdf', name: 'pattern-a0.pdf', label: 'pattern-a0.pdf', note: 'Full scale using the configured paper settings.' },
  { path: '/api/patterns/export/dxf', name: 'pattern.dxf', label: 'pattern.dxf', note: 'Full scale, millimetres.' },
  { path: '/api/patterns/export/svg', name: 'pattern-preview.svg', label: 'pattern-preview.svg', note: 'The sewing and cutting geometry preview.' },
]

export function ExportView({
  result,
  input,
  settings,
}: {
  result: GenerationResponse
  input: GenerationPayload
  settings: Settings
}) {
  const [busy, setBusy] = useState<string | null>(null)
  const [error, setError] = useState<string | null>(null)
  const blocked = result.validation.status !== 'pass'

  const download = async (path: string, name: string) => {
    setBusy(name)
    setError(null)
    try {
      await api.download(path, name, input, settings)
    } catch (e) {
      setError(e instanceof RequestError ? `${e.message}${e.details.length ? `: ${e.details.map((d) => d.message).join('; ')}` : ''}` : 'Export failed')
    } finally {
      setBusy(null)
    }
  }

  return (
    <div className="stack">
      <h2>Production exports</h2>
      {blocked ? (
        <Callout tone="error" title="Production export blocked">
          Critical geometric validation failed. Review the validation report and regenerate
          before producing production files.
        </Callout>
      ) : null}

      <div className="export-grid">
        {FILES.map((file) => (
          <div key={file.name} className="export-card">
            <div>
              <strong>{file.label}</strong>
              <small>{file.note}</small>
            </div>
            <Button
              variant="primary"
              disabled={busy !== null || blocked}
              onClick={() => void download(file.path, file.name)}
            >
              {busy === file.name ? 'Preparing…' : 'Download'}
            </Button>
          </div>
        ))}
        <div className="export-card">
          <div>
            <strong>pattern.json</strong>
            <small>GarmageSet-like primary pattern document.</small>
          </div>
          <Button disabled={busy !== null} onClick={() => saveJson('pattern.json', result.pattern)}>Download</Button>
        </div>
        <div className="export-card">
          <div>
            <strong>generation-manifest.json</strong>
            <small>Measurement interpretations, configuration, levels, assumptions, and provenance.</small>
          </div>
          <Button disabled={busy !== null} onClick={() => saveJson('generation-manifest.json', result.trace)}>Download</Button>
        </div>
        <div className="export-card">
          <div>
            <strong>flattening-diagnostics.json</strong>
            <small>Per-panel distortion, solver status, seam balance, and reconstruction residuals.</small>
          </div>
          <Button disabled={busy !== null} onClick={() => saveJson('flattening-diagnostics.json', result.diagnostics)}>Download</Button>
        </div>
        <div className="export-card">
          <div>
            <strong>validation-report.json</strong>
            <small>Geometric checks, tolerances, and measured metrics.</small>
          </div>
          <Button disabled={busy !== null} onClick={() => saveJson('validation-report.json', result.validation)}>Download</Button>
        </div>
      </div>

      {error ? <Callout tone="error" title="Export failed">{error}</Callout> : null}

      <Callout tone="info" title="Pattern provenance">
        <p>
          The pattern was generated by <code>{result.trace.method}</code> from{' '}
          <code>{result.trace.source_file}</code>. Source values were interpreted as{' '}
          {result.trace.units.source} and pattern coordinates are in {result.trace.units.pattern}.
          The generation manifest records all assumptions and configuration versions.
        </p>
      </Callout>
    </div>
  )
}
